export function translate(value, locale = "zh") {
  const text = normalize(value);
  if (typeof text !== "string" || locale === "zh") return value;
  return zhToEn.get(text) ?? dynamic(text, locale);
}

export function applyLocale(locale) {
  const language = locale === "en" ? "en" : "zh";
  document.documentElement.lang = language === "en" ? "en" : "zh-CN";
  document.title = language === "en" ? "Last Train · Online Preview" : "最后一班 · 联机试验";
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.parentElement?.closest("[data-no-translate],script,style")) continue;
    const before = node.nodeValue;
    const trimmed = before.trim();
    if (!trimmed) continue;
    const translated = language === "en"
      ? zhToEn.get(trimmed) ?? dynamic(trimmed, language)
      : enToZh.get(trimmed) ?? dynamic(trimmed, language);
    if (translated !== trimmed)
      node.nodeValue = before.replace(trimmed, translated);
  }
  for (const input of document.querySelectorAll("input[placeholder]")) {
    const value = language === "en"
      ? zhToEn.get(input.placeholder) ?? input.placeholder
      : enToZh.get(input.placeholder) ?? input.placeholder;
    input.placeholder = value;
  }
  const picker = document.getElementById("language");
  if (picker) {
    picker.setAttribute("aria-label", language === "en" ? "Interface language" : "界面语言");
    for (const option of picker.options) {
      option.textContent = option.value === "en" ? "English" : "中文";
    }
    picker.value = language;
  }
}
